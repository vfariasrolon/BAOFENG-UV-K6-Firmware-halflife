void LCD_DrawLogo(void)
{
    U8 x, y, byte, bit;
    
    for (y = 0; y < 64; y++) {
        for (x = 0; x < 128; x++) {
            byte = halflife_logo_128x64[(y * 16) + (x / 8)];
            bit = (byte & (0x80 >> (x % 8))) ? 1 : 0;
            LCD_DrawPixel(x, y, bit);
        }
    }
}
